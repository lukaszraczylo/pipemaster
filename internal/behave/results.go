//go:build behave

package behave

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

const (
	cellNone    = "-"
	detailLimit = 280
)

func cell(r *Result) string {
	switch r.Status {
	case StatusPass:
		return "pass"
	case StatusExplained:
		return "diff"
	case StatusFail:
		return "FAIL"
	}
	return "blocked"
}

func mdEscape(s string) string {
	s = strings.ReplaceAll(s, "|", "/")
	s = strings.ReplaceAll(s, "\n", " ")
	if len(s) > detailLimit {
		s = s[:detailLimit] + "..."
	}
	return s
}

// Counts totals the cells by status.
func Counts(rs []Result) map[string]int {
	c := map[string]int{}
	for _, r := range rs {
		c[r.Status]++
	}
	return c
}

// Failures returns the unexplained differences.
func Failures(rs []Result) []Result {
	var out []Result
	for _, r := range rs {
		if r.Status == StatusFail {
			out = append(out, r)
		}
	}
	return out
}

func sortResults(rs []Result) {
	sort.Slice(rs, func(i, j int) bool {
		a, b := rs[i], rs[j]
		for _, p := range [][2]string{{a.Source, b.Source}, {a.Fixture, b.Fixture}, {a.Event, b.Event}, {a.Target, b.Target}} {
			if p[0] != p[1] {
				return p[0] < p[1]
			}
		}
		return false
	})
}

// RenderMarkdown writes the RESULTS.md matrix. It holds no timestamp, so two identical runs give one file.
func RenderMarkdown(rs []Result, times map[string]EngineTime) string {
	sortResults(rs)
	var b strings.Builder
	c := Counts(rs)
	b.WriteString("# Behavioural results\n\n")
	b.WriteString("Generated by `make behave`. Each cell compares the trace of a converted pipeline on its target engine with the trace of the source pipeline on its own engine.\n\n")
	fmt.Fprintf(&b, "Totals: %d pass, %d diff (explained by the loss report), %d FAIL (unexplained), %d blocked.\n\n", c[StatusPass], c[StatusExplained], c[StatusFail], c[StatusBlocked])
	b.WriteString("- `pass`: same ordered markers and same exit code.\n")
	b.WriteString("- `diff`: every difference has a loss report entry of the right job or step and of a kind that can cause it (the rule is printed in the diff list).\n")
	b.WriteString("- `FAIL`: a difference that no loss report entry explains. The converter is wrong.\n")
	b.WriteString("- `blocked`: the engine cannot judge the pair (see the blocked list). Blocked cells are unverified, not clean.\n\n")

	bySrc := map[string][]Result{}
	for _, r := range rs {
		bySrc[r.Source] = append(bySrc[r.Source], r)
	}
	var srcs []string
	for s := range bySrc {
		srcs = append(srcs, s)
	}
	sort.Strings(srcs)
	for _, s := range srcs {
		fmt.Fprintf(&b, "## Source %s\n\n| fixture | event |", s)
		for _, t := range Targets {
			fmt.Fprintf(&b, " %s |", t)
		}
		b.WriteString("\n|---|---|")
		for range Targets {
			b.WriteString("---|")
		}
		b.WriteString("\n")
		type key struct{ fx, ev string }
		rows := map[key]map[string]*Result{}
		var order []key
		for i := range bySrc[s] {
			r := &bySrc[s][i]
			k := key{r.Fixture, r.Event}
			if rows[k] == nil {
				rows[k] = map[string]*Result{}
				order = append(order, k)
			}
			rows[k][r.Target] = r
		}
		for _, k := range order {
			fmt.Fprintf(&b, "| %s | %s |", k.fx, k.ev)
			for _, t := range Targets {
				if r := rows[k][t]; r != nil {
					fmt.Fprintf(&b, " %s |", cell(r))
				} else {
					fmt.Fprintf(&b, " %s |", cellNone)
				}
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	section(&b, "Unexplained differences (FAIL)", rs, StatusFail, false)
	section(&b, "Differences explained by the loss report", rs, StatusExplained, true)
	blockedSection(&b, rs)
	capabilitySection(&b)
	b.WriteString("## Engine run times\n\n| engine | runs | total | mean |\n|---|---|---|---|\n")
	var names []string
	for n := range times {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		t := times[n]
		mean := time.Duration(0)
		if t.Runs > 0 {
			mean = t.Total / time.Duration(t.Runs)
		}
		fmt.Fprintf(&b, "| %s | %d | %s | %s |\n", n, t.Runs, t.Total.Round(time.Second), mean.Round(100*time.Millisecond))
	}
	b.WriteString("\nRun times vary with the machine and are the only part of this file that changes between identical runs.\n")
	return b.String()
}

func section(b *strings.Builder, title string, rs []Result, status string, explained bool) {
	fmt.Fprintf(b, "## %s\n\n", title)
	n := 0
	for _, r := range rs {
		if r.Status != status {
			continue
		}
		n++
		line := fmt.Sprintf("- %s -> %s, fixture %s, event %s: %s", r.Source, r.Target, r.Fixture, r.Event, mdEscape(r.Detail))
		if explained {
			line += " (explained by: " + r.Explained + ")"
		}
		b.WriteString(line + "\n")
	}
	if n == 0 {
		b.WriteString("None.\n")
	}
	b.WriteString("\n")
}

func blockedSection(b *strings.Builder, rs []Result) {
	b.WriteString("## Blocked pairs\n\n")
	groups := map[string][]string{}
	for _, r := range rs {
		if r.Status != StatusBlocked {
			continue
		}
		reason := r.Detail
		if i := strings.Index(reason, ":"); i > 0 && i < 60 && strings.HasPrefix(reason, "the source failed") {
			reason = reason[:i]
		}
		reason = mdEscape(reason)
		groups[reason] = append(groups[reason], fmt.Sprintf("%s->%s %s/%s", r.Source, r.Target, r.Fixture, r.Event))
	}
	if len(groups) == 0 {
		b.WriteString("None.\n\n")
		return
	}
	var reasons []string
	for k := range groups {
		reasons = append(reasons, k)
	}
	sort.Strings(reasons)
	for _, k := range reasons {
		cells := groups[k]
		sort.Strings(cells)
		fmt.Fprintf(b, "- %d cells: %s\n", len(cells), k)
		if len(cells) <= 12 {
			fmt.Fprintf(b, "  - %s\n", strings.Join(cells, ", "))
		}
	}
	b.WriteString("\n")
}

func capabilitySection(b *strings.Builder) {
	b.WriteString("## Engine capabilities\n\n")
	for _, p := range Targets {
		c := capsOf(p)
		var notes []string
		if c.events != nil {
			notes = append(notes, fmt.Sprintf("events %s (%s)", strings.Join(c.events, ", "), c.eventWhy))
		}
		if c.noSHA {
			notes = append(notes, "no commit SHA: drone exec ignores DRONE_COMMIT_SHA from its flags, its env file and the process environment, so the env.sha marker is not compared on a pair with drone")
		}
		for req, why := range c.unsupported {
			notes = append(notes, fmt.Sprintf("%s unsupported (%s)", req, why))
		}
		if len(notes) > 0 {
			fmt.Fprintf(b, "- %s: %s\n", p, strings.Join(notes, "; "))
		}
	}
	fmt.Fprintf(b, "- gha: a workflow with a job that has continue-on-error and a dependent job is blocked (%s)\n\n", jobContinueWhy)
}
